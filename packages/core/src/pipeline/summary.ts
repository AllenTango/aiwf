/** 结项报告(deliverable.summary)构建:纯函数,含状态符号与冲突解析。 */

import type { PlanVerdict, TaskResult, TaskStatus, WorkflowPlan } from '../contracts/index.js';
import { clampLine, mdCell } from './md.js';

/** ✔ / △ / ✘ 状态符号。 */
export const STATUS_MARK: Record<TaskStatus, string> = {
  completed: '✔',
  partial: '△',
  failed: '✘',
};

/** 一次成员分支合并失败的记录。 */
export interface MergeConflict {
  branch: string;
  /** 承担该分支的任务 ID(可追溯)。 */
  taskId: string | null;
  /** 从 git 错误信息中解析出的冲突文件列表。 */
  files: string[];
  /** 原始错误信息。 */
  message: string;
}

/** 从 merge 错误信息里提取 `Merge conflict in <file>` 行。 */
export function parseConflictFiles(message: string): string[] {
  const files: string[] = [];
  for (const match of message.matchAll(/Merge conflict in\s+(\S+)/g)) {
    const file = match[1];
    if (file !== undefined && !files.includes(file)) {
      files.push(file);
    }
  }
  return files;
}

/** 整体状态:全失败 → failed;有冲突或非完成 → partial;否则 completed。 */
export function overallStatus(
  results: readonly TaskResult[],
  conflicts: readonly MergeConflict[],
): TaskStatus {
  if (results.length === 0 && conflicts.length === 0) return 'completed';
  if (results.length > 0 && results.every((r) => r.status === 'failed')) return 'failed';
  if (conflicts.length > 0) return 'partial';
  if (results.some((r) => r.status !== 'completed')) return 'partial';
  return 'completed';
}

export interface DeliverSummaryInput {
  plan: WorkflowPlan;
  results: readonly TaskResult[];
  conflicts: readonly MergeConflict[];
  dryRun?: boolean;
}

/** 裁决标题(reject / need_clarification)。 */
export const VERDICT_TITLE: Record<Exclude<PlanVerdict, 'proceed'>, string> = {
  reject: '不予开工(reject)',
  need_clarification: '需要澄清(need_clarification)',
};

/**
 * 队长裁决的结项摘要(reject / need_clarification 时的 deliverable.summary)。
 *
 * 语义:这一轮**没有派发任何队员**,因此没有代码变更、没有 PR。
 * 摘要必须让人一眼看懂「为什么没干活」和「下一步该做什么」。
 */
export function buildVerdictSummary(plan: WorkflowPlan, verdict: Exclude<PlanVerdict, 'proceed'>): string {
  const lines: string[] = [`## 队长裁决:${VERDICT_TITLE[verdict]}`, ''];
  lines.push(`整体结论:**${clampLine(plan.summary, 300)}**`);
  if (plan.rationale !== undefined && plan.rationale !== '') {
    lines.push('', '### 判断依据', clampLine(plan.rationale, 1200));
  }
  if (plan.analysis !== undefined) {
    const a = plan.analysis;
    if (a.understanding !== '') {
      lines.push('', '### 对需求与现状的理解', clampLine(a.understanding, 800));
    }
    if (a.affectedAreas.length > 0) {
      lines.push('', '### 预计受影响的区域', ...a.affectedAreas.map((x) => `- ${clampLine(x, 120)}`));
    }
    if (a.risks.length > 0) {
      lines.push('', '### 分析阶段识别的风险', ...a.risks.map((x) => `- ${clampLine(x, 200)}`));
    }
  }
  if (verdict === 'need_clarification' && (plan.clarifications?.length ?? 0) > 0) {
    lines.push('', '### 需要你回答的问题');
    for (const [i, q] of (plan.clarifications ?? []).entries()) {
      lines.push(`${i + 1}. ${clampLine(q, 300)}`);
    }
    lines.push('', '> 回答这些问题后重新触发本流水线即可继续。');
  }
  if (verdict === 'reject') {
    lines.push('', '### 后续建议', '本次未派发任何队员,未消耗成员模型调用。若上述结论有误,可在评论中说明理由后重新触发。');
  }
  if (plan.cost !== undefined) {
    lines.push(
      '',
      `> 成本估计:量级 ${plan.cost.weight} · 预计调用 ${plan.cost.expectedCalls} 次` +
        (plan.cost.units !== undefined ? ` · 相对成本 ${plan.cost.units} 单位` : '') +
        (plan.cost.reason !== '' ? ` · ${clampLine(plan.cost.reason, 200)}` : ''),
    );
  }
  return lines.join('\n');
}

/**
 * 队长裁决回帖到任务源的评论正文(人类在 Issue 上直接看到)。
 */
export function buildVerdictComment(plan: WorkflowPlan, verdict: Exclude<PlanVerdict, 'proceed'>): string {
  const head =
    verdict === 'reject'
      ? '🤖 **AI 队长裁决:本次不予开工**'
      : '🤖 **AI 队长:需要你澄清几点才能开工**';
  const parts: string[] = [head, ''];
  parts.push(`> ${clampLine(plan.summary, 300)}`);
  if (plan.rationale !== undefined && plan.rationale !== '') {
    parts.push('', '**判断依据**', clampLine(plan.rationale, 1200));
  }
  if (verdict === 'need_clarification' && (plan.clarifications?.length ?? 0) > 0) {
    parts.push('', '**需要你回答**');
    for (const [i, q] of (plan.clarifications ?? []).entries()) {
      parts.push(`${i + 1}. ${clampLine(q, 300)}`);
    }
    parts.push('', '_回答后重新触发本流水线即可继续;本次未派发任何队员。_');
  } else {
    parts.push('', '_本次未派发任何队员,未消耗成员模型调用。_');
  }
  parts.push('', '_Generated by ai-dev-workflow-action_');
  return parts.join('\n');
}

/**
 * 队长的结项报告,包含:整体状态、计划概要、逐任务状态表(✔/△/✘)、
 * 冲突与跳过清单、risks。dryRun 时末尾追加 "(dry-run)" 标记。
 */
export function buildDeliverSummary(input: DeliverSummaryInput): string {
  const { plan, results, conflicts, dryRun = false } = input;
  const counts: Record<TaskStatus, number> = { completed: 0, partial: 0, failed: 0 };
  for (const r of results) counts[r.status] += 1;
  const status = overallStatus(results, conflicts);

  const lines: string[] = ['## 结项报告', ''];
  lines.push(
    `整体状态:**${status}**(成功 ${counts.completed} / 部分 ${counts.partial} / 失败 ${counts.failed} / 合并冲突 ${conflicts.length})`,
  );
  lines.push('', '### 计划概要', plan.summary === '' ? '(计划未提供摘要)' : plan.summary);
  lines.push('', '### 任务状态');
  if (results.length === 0) {
    lines.push('本次运行没有成员任务。');
  } else {
    lines.push('| 任务 | 角色 | 状态 | 摘要 |', '| --- | --- | --- | --- |');
    for (const r of results) {
      const role = plan.tasks.find((t) => t.id === r.taskId)?.role ?? '-';
      const digest = r.error ?? clampLine(r.summary, 200);
      lines.push(`| ${r.taskId} | ${role} | ${STATUS_MARK[r.status]} ${r.status} | ${mdCell(digest)} |`);
    }
  }

  const skipped = results.filter(
    (r) => typeof r.error === 'string' && r.error.startsWith('skipped:'),
  );
  lines.push('', '### 冲突与跳过');
  if (conflicts.length === 0 && skipped.length === 0) {
    lines.push('无合并冲突,无跳过任务。');
  } else {
    for (const c of conflicts) {
      const filePart = c.files.length > 0 ? `,冲突文件:${c.files.join('、')}` : '';
      lines.push(
        `- 合并冲突:\`${c.branch}\`${c.taskId === null ? '' : `(任务 ${c.taskId})`}${filePart} — ${clampLine(c.message, 200)}`,
      );
    }
    for (const s of skipped) {
      lines.push(`- 跳过:${s.taskId} — ${clampLine(s.error ?? '依赖链失败', 200)}`);
    }
  }

  lines.push('', '### 风险');
  if (plan.risks.length === 0) {
    lines.push('无已识别风险。');
  } else {
    for (const risk of plan.risks) lines.push(`- ${risk}`);
  }

  if (dryRun) {
    lines.push('', '> (dry-run) 本次运行为演练模式:未执行成员任务、未创建分支、未发起 Pull Request。');
  }
  return lines.join('\n');
}
