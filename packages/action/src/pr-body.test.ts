import { describe, expect, it } from 'vitest';
import type { TaskInput, TaskResult, WorkflowPlan } from '@aiwf/core';
import { buildPullRequestBody, STATUS_EMOJI } from './pr-body.js';

const baseTask: TaskInput = {
  source: 'issue',
  ref: 'acme/team#7',
  title: '实现用户登录接口',
  body: '需要提供 /api/login 接口\n支持 JWT,返回 access token。',
  comments: ['@aiwf 请补充超时与重试策略', '评审提醒:注意频控'],
};

const basePlan: WorkflowPlan = {
  summary: '两条支线:后端接口实现 + 客户端联调',
  tasks: [
    {
      id: 't1',
      title: '后端接口',
      role: 'implementer',
      instructions: '……',
      dependsOn: [],
      expectedOutputs: ['packages/server/**'],
    },
    {
      id: 't2',
      title: '客户端联调',
      role: 'integrator',
      instructions: '……',
      dependsOn: ['t1'],
      expectedOutputs: ['web/**'],
    },
  ],
  risks: ['第三方验证码服务不稳定', '登录频控可能误伤内网'],
};

const baseResults: TaskResult[] = [
  {
    taskId: 't1',
    status: 'completed',
    summary: '完成 /api/login 与单测',
    changedFiles: [
      { path: 'packages/server/login.ts', action: 'add' },
      { path: 'packages/server/package.json', action: 'modify' },
    ],
    notes: [],
  },
  {
    taskId: 't2',
    status: 'partial',
    summary: '前端联调已接通,遗留两处类型收敛',
    changedFiles: [{ path: 'web/login.tsx', action: 'add' }],
    notes: [],
  },
  {
    taskId: 't3',
    status: 'failed',
    summary: '评审代理未执行',
    changedFiles: [],
    notes: [],
    error: 'engine timeout after 30s',
  },
];

const baseSummary = '登录接口已交付;联调遗留收敛为两处类型问题。';

function build(
  overrides: {
    task?: Partial<TaskInput>;
    plan?: Partial<WorkflowPlan>;
    results?: TaskResult[];
    summary?: string;
  } = {},
): string {
  return buildPullRequestBody(
    { ...baseTask, ...overrides.task },
    { ...basePlan, ...overrides.plan },
    overrides.results ?? baseResults,
    overrides.summary ?? baseSummary,
  );
}

/** 取某标题段落到下一个 "## " 之间或末尾的文本片段。 */
function sliceSection(body: string, startHeading: string, followingHeadings: string[]): string {
  const startIndex = body.indexOf(startHeading);
  expect(startIndex, `正文中应存在标题 ${startHeading}`).toBeGreaterThanOrEqual(0);
  const upperBound = followingHeadings.length === 0
    ? Number.POSITIVE_INFINITY
    : followingHeadings
        .map((heading) => {
          const index = body.indexOf(heading, startIndex + 1);
          return index === -1 ? Number.POSITIVE_INFINITY : index;
        })
        .reduce((left, right) => Math.min(left, right), Number.POSITIVE_INFINITY);
  return body.slice(startIndex, upperBound === Number.POSITIVE_INFINITY ? undefined : upperBound);
}

describe('buildPullRequestBody(全段落)', () => {
  it('按固定顺序包含全部六个段落 + 署名行', () => {
    const body = build();
    expect(body.indexOf('## 🧾 诉求')).toBeLessThan(body.indexOf('## 🧭 方案(队长规划)'));
    expect(body.indexOf('## 🧭 方案(队长规划)')).toBeLessThan(body.indexOf('## 🔧 执行明细'));
    expect(body.indexOf('## 🔧 执行明细')).toBeLessThan(body.indexOf('## 📦 变更文件'));
    expect(body.indexOf('## 📦 变更文件')).toBeLessThan(body.indexOf('## ⚠️ 风险与注意'));
    expect(body.indexOf('## ⚠️ 风险与注意')).toBeLessThan(body.indexOf('## 🏁 结论'));
    expect(body.trimEnd().endsWith('_Generated by ai-dev-workflow-action_')).toBe(true);
  });

  it('诉求段:标题加粗、正文摘要、来源与评论计数', () => {
    const body = build();
    const section = sliceSection(body, '## 🧾 诉求', ['## 🧭 方案(队长规划)']);
    expect(section).toContain('**实现用户登录接口**');
    expect(section).toContain('需要提供 /api/login 接口');
    expect(section).toContain('支持 JWT');
    expect(section).toContain('acme/team#7');
    expect(section).toContain('> 追加评论 2 条');
    expect(section).toContain('@aiwf 请补充超时与重试策略');
    expect(section).toContain('评审提醒:注意频控');
  });

  it('诉求段:超过 3 条评论时其余折叠为计数', () => {
    const body = build({
      task: {
        comments: [
          '第一条评论',
          '第二条评论',
          '第三条评论',
          '第四条评论',
          '第五条评论',
        ],
      },
    });
    const section = sliceSection(body, '## 🧾 诉求', ['## 🧭 方案(队长规划)']);
    expect(section).toContain('> 追加评论 5 条:');
    expect(section).toContain('…另 2 条见源任务');
  });

  it('方案段包含队长 summary', () => {
    const body = build();
    const section = sliceSection(body, '## 🧭 方案(队长规划)', ['## 🔧 执行明细']);
    expect(section).toContain('两条支线:后端接口实现 + 客户端联调');
  });

  it('执行明细:状态表含角色、状态标记与失败详情', () => {
    const body = build();
    const section = sliceSection(body, '## 🔧 执行明细', ['## 📦 变更文件']);
    expect(section).toContain('| 任务 | 角色 | 状态 | 摘要 |');
    expect(section).toContain('| t1 · 后端接口 | implementer | ✔ completed | 完成 /api/login 与单测 |');
    expect(section).toContain('| t2 · 客户端联调 | integrator | △ partial | 前端联调已接通,遗留两处类型收敛 |');
    expect(section).toContain('| t3 · ');
    expect(section).toContain('✘ failed');
    expect(section).toContain('(失败原因:engine timeout after 30s)');
  });

  it('变更文件:总数分类计数与路径清单', () => {
    const body = build();
    const section = sliceSection(body, '## 📦 变更文件', ['## ⚠️ 风险与注意']);
    expect(section).toContain('共 3 个文件(新增 2 · 修改 1 · 删除 0)');
    expect(section).toContain('- 新增 `packages/server/login.ts`');
    expect(section).toContain('- 修改 `packages/server/package.json`');
    expect(section).toContain('- 新增 `web/login.tsx`');
  });

  it('变更文件:跨成员同路径去重,不重复计数', () => {
    const body = build();
    const section = sliceSection(body, '## 📦 变更文件', ['## ⚠️ 风险与注意']);
    expect(section).not.toContain('- 新增 `web/login.tsx`\n- 新增 `web/login.tsx`');
  });

  it('变更文件清单超过 10 条时截断为 top10,但总数如实', () => {
    const many = baseResults[0]!;
    const lots = [many, { ...many, taskId: 't9' }];
    // 直接构造 14 个不同路径的成员结果
    const results: TaskResult[] = [
      {
        taskId: 't1',
        status: 'completed',
        summary: '样例',
        changedFiles: [], // 占位,下方填充
        notes: [],
      },
      {
        taskId: 't1',
        status: 'completed',
        summary: '样例',
        changedFiles: Array.from({ length: 14 }, (_, index) => ({
          path: `src/file-${index}.ts`,
          action: 'modify' as const,
        })),
        notes: [],
      },
      ...lots.map((result) => ({ ...result, changedFiles: [] })),
    ];
    const body = build({ results });
    const section = sliceSection(body, '## 📦 变更文件', ['## ⚠️ 风险与注意']);
    expect(section).toContain('共 14 个文件(新增 0 · 修改 14 · 删除 0)');
    expect(section).toContain('列前 10 个');
    expect(section.split('\n').filter((line) => line.startsWith('- ')).length).toBe(10);
    expect(section).toContain('- 修改 `src/file-0.ts`');
    expect(section).not.toContain('`src/file-13.ts`');
  });

  it('风险段逐条列出', () => {
    const body = build();
    const section = sliceSection(body, '## ⚠️ 风险与注意', ['## 🏁 结论']);
    expect(section).toContain('- 第三方验证码服务不稳定');
    expect(section).toContain('- 登录频控可能误伤内网');
  });

  it('无风险时提示未上报', () => {
    const body = build({ plan: { risks: [] } });
    const section = sliceSection(body, '## ⚠️ 风险与注意', ['## 🏁 结论']);
    expect(section).toContain('未上报风险项');
  });

  it('结论段包含队长结项摘要', () => {
    const body = build();
    const section = sliceSection(body, '## 🏁 结论', []);
    expect(section).toContain('登录接口已交付');
    expect(section).toContain('联调遗留收敛为两处类型问题');
  });

  it('特殊字符:summary 内竖线被转义、换行被折叠(不破坏表格)', () => {
    const body = build({
      results: [
        {
          taskId: 't1',
          status: 'completed',
          summary: '第一行\n第二行 | 影响表格 | 需转义',
          changedFiles: [],
          notes: [],
        },
      ],
    });
    const section = sliceSection(body, '## 🔧 执行明细', ['## 📦 变更文件']);
    expect(section).toContain('第一行 第二行 \\| 影响表格 \\| 需转义');
  });

  it('dry_run / 全 mock 场景:零成果时表格与变更段给出占位说明且不抛错', () => {
    const body = build({ results: [] });
    const resultsSection = sliceSection(body, '## 🔧 执行明细', ['## 📦 变更文件']);
    expect(resultsSection).toContain('| — | — | — | 无成员成果');
    const filesSection = sliceSection(body, '## 📦 变更文件', ['## ⚠️ 风险与注意']);
    expect(filesSection).toContain('无结构化变更记录');
  });

  it('STATUS_EMOJI 文案:完成✔ partial△ failed✘', () => {
    expect(STATUS_EMOJI).toEqual({ completed: '✔', partial: '△', failed: '✘' });
  });
});
