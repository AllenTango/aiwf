/**
 * @aiwf/action — 结项 PR 正文构造(纯函数,无 IO、无时钟依赖,可确定性测试)。
 * OWNER: M4.
 *
 * 段落结构(与 M3 的 CLI 结项报告保持同构,便于未来下沉到 core 统一):
 *   诉求 / 方案 / 执行明细(状态表)/ 变更文件汇总 / 风险 / 结论 / 署名行。
 */
import type {
  ChangedFileAction,
  TaskInput,
  TaskResult,
  TaskStatus,
  WorkflowPlan,
} from '@aiwf/core';

/** TaskStatus → 状态标记(完成✔ partial△ failed✘)。 */
export const STATUS_EMOJI: Record<TaskStatus, string> = {
  completed: '✔',
  partial: '△',
  failed: '✘',
};

/** task.body 摘要截断长度。 */
const REQUEST_BODY_LIMIT = 600;
/** 追加评论回显截断长度。 */
const COMMENT_PREVIEW_LIMIT = 160;
/** 评论回显最多条数(其余以计数表述)。 */
const MAX_COMMENTS_LISTED = 3;
/** 变更文件清单最多条数。 */
const MAX_CHANGED_FILES_LISTED = 10;

const CHANGE_ACTION_LABEL: Record<ChangedFileAction, string> = {
  add: '新增',
  modify: '修改',
  delete: '删除',
};

/** 折叠为一行(去 CR/LF)。 */
function oneLine(text: string): string {
  return text.replace(/\r/g, '').replace(/\n+/g, ' ').trim();
}

/** 内联文本/markdown 强调单元素转义(竖线)并保单行。 */
function inlineText(text: string): string {
  return oneLine(text).replace(/\|/g, '\\|');
}

/** 表格单元格转义(竖线)并保单行。 */
function tableCell(text: string): string {
  return inlineText(text);
}

/** 按字符数截断,溢出以 … 结尾。 */
function truncate(text: string, limit: number): string {
  const single = oneLine(text);
  if (single.length <= limit) {
    return single;
  }
  return `${single.slice(0, limit - 1)}…`;
}

/**
 * 构造结项 PR 正文。
 *
 * @param task    原始诉求(标题/正文/追加评论,来自 platform.fetchTask)
 * @param plan    队长规划(含 risks)
 * @param results 各成员 TaskResult(顺序即计划调度顺序)
 * @param summary 队长结项摘要(deliverable.summary)
 */
export function buildPullRequestBody(
  task: TaskInput,
  plan: WorkflowPlan,
  results: readonly TaskResult[],
  summary: string,
): string {
  const sections: string[] = [
    renderRequestSection(task),
    renderPlanSection(plan),
    renderResultsSection(plan, results),
    renderChangedFilesSection(results),
    renderRisksSection(plan),
    renderConclusionSection(summary),
  ];
  return `${sections.join('\n\n')}\n\n_Generated by ai-dev-workflow-action_`;
}

function renderRequestSection(task: TaskInput): string {
  const lines: string[] = ['## 🧾 诉求'];
  const title = inlineText(task.title);
  if (title !== '') {
    lines.push('', `**${title}**`);
  }
  const bodySummary = truncate(task.body, REQUEST_BODY_LIMIT);
  if (bodySummary !== '') {
    lines.push('', bodySummary);
  }

  const sourceLine = task.ref ?? '';
  const issueUrl = task.metadata?.issueUrl;
  lines.push(
    '',
    `> 任务来源:${task.source}${sourceLine !== '' ? ` · ${sourceLine}` : ''}${
      issueUrl !== undefined ? `(${issueUrl})` : ''
    }`,
  );

  const comments = task.comments ?? [];
  if (comments.length > 0) {
    lines.push('', `> 追加评论 ${comments.length} 条:`);
    for (const comment of comments.slice(0, MAX_COMMENTS_LISTED)) {
      lines.push(`> - ${inlineText(truncate(comment, COMMENT_PREVIEW_LIMIT))}`);
    }
    if (comments.length > MAX_COMMENTS_LISTED) {
      lines.push(`> - …另 ${comments.length - MAX_COMMENTS_LISTED} 条见源任务`);
    }
  }
  return lines.join('\n');
}

function renderPlanSection(plan: WorkflowPlan): string {
  return ['## 🧭 方案(队长规划)', '', oneLine(plan.summary)].join('\n');
}

function renderResultsSection(plan: WorkflowPlan, results: readonly TaskResult[]): string {
  const lines: string[] = [
    '## 🔧 执行明细',
    '',
    '| 任务 | 角色 | 状态 | 摘要 |',
    '| --- | --- | --- | --- |',
  ];
  if (results.length === 0) {
    lines.push('| — | — | — | 无成员成果(可能为 dry_run 或规划失败)|');
    return lines.join('\n');
  }
  const taskById = new Map(plan.tasks.map((planned) => [planned.id, planned] as const));
  for (const result of results) {
    const planned = taskById.get(result.taskId);
    const title = planned?.title ?? '(未在计划中)';
    const role = planned?.role ?? '-';
    let summaryText = tableCell(result.summary);
    if (result.status === 'failed' && typeof result.error === 'string' && result.error !== '') {
      summaryText = `${summaryText}(失败原因:${tableCell(result.error)})`;
    }
    lines.push(
      `| ${inlineText(result.taskId)} · ${inlineText(title)} | ${inlineText(role)} | ${
        STATUS_EMOJI[result.status]
      } ${result.status} | ${summaryText} |`,
    );
  }
  return lines.join('\n');
}

function renderChangedFilesSection(results: readonly TaskResult[]): string {
  const byPath = new Map<string, ChangedFileAction>();
  const counts: Record<ChangedFileAction, number> = { add: 0, modify: 0, delete: 0 };
  for (const result of results) {
    for (const file of result.changedFiles ?? []) {
      if (byPath.has(file.path)) {
        continue;
      }
      byPath.set(file.path, file.action);
      counts[file.action] += 1;
    }
  }
  const total = byPath.size;
  const lines: string[] = ['## 📦 变更文件'];
  if (total === 0) {
    lines.push('', '无结构化变更记录(可能仅完成讨论或检查)。');
    return lines.join('\n');
  }
  const listed = [...byPath.entries()].slice(0, MAX_CHANGED_FILES_LISTED);
  lines.push(
    '',
    `共 ${total} 个文件(新增 ${counts.add} · 修改 ${counts.modify} · 删除 ${counts.delete}),列前 ${listed.length} 个:`,
    '',
  );
  for (const [path, action] of listed) {
    lines.push(`- ${CHANGE_ACTION_LABEL[action]} \`${path}\``);
  }
  return lines.join('\n');
}

function renderRisksSection(plan: WorkflowPlan): string {
  const lines: string[] = ['## ⚠️ 风险与注意'];
  const risks = plan.risks ?? [];
  if (risks.length === 0) {
    lines.push('', '未上报风险项。');
    return lines.join('\n');
  }
  lines.push('');
  for (const risk of risks) {
    lines.push(`- ${inlineText(risk)}`);
  }
  return lines.join('\n');
}

function renderConclusionSection(summary: string): string {
  return ['## 🏁 结论', '', oneLine(summary)].join('\n');
}
